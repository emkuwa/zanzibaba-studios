// Interpolation helper
function tpl(s: string, vars: Record<string, string>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}

export function tSeo<K extends keyof typeof en>(locale: 'en' | 'sw', key: K, vars?: Record<string, string>): string {
  const dict = locale === 'sw' ? sw : en;
  const raw = dict[key] as string;
  return vars ? tpl(raw, vars) : raw;
}
